// Icon Renderer
function renderIcon(name, size = 20, color = 'currentColor') {
    const svg = Icons[name];
    if (!svg) return '';
    
    return svg.replace('<svg', `<svg width="${size}" height="${size}" style="color: ${color}; flex-shrink: 0;"`);
}

// Create icon element
function createIcon(name, size = 20, color = 'currentColor') {
    const div = document.createElement('div');
    div.className = 'icon';
    div.style.cssText = `width:${size}px;height:${size}px;display:inline-flex;align-items:center;justify-content:center;flex-shrink:0;`;
    div.innerHTML = renderIcon(name, size, color);
    return div;
}

// Initialize all icon placeholders
function initIcons() {
    document.querySelectorAll('[data-icon]').forEach(el => {
        const name = el.dataset.icon;
        const size = el.dataset.iconSize || 20;
        const color = el.dataset.iconColor || 'currentColor';
        el.innerHTML = renderIcon(name, size, color);
    });
}